import { afterEach, test } from 'node:test';
import assert from 'node:assert/strict';
import { FloClient, FloError, floError, retryAfterOf } from '../src/flo/client.js';
import { HttpError, NetworkError, request, setFetch } from '../src/http.js';
import { EMAIL, NOW, PASSWORD, installFlo, json } from './helpers/fakeFlo.js';

let fake;
afterEach(() => fake?.restore());

const httpError = (status, text = '', headers = {}) =>
  new HttpError(status, 'https://api-gw.meetflo.com/api/v2/x?secret=1', text, new Headers(headers));

test('errors: refused, unauthorized, passing ones', () => {
  assert.equal(floError(httpError(401), { signIn: true }).kind, 'refused');
  assert.equal(floError(httpError(400), { signIn: true }).kind, 'refused');
  assert.equal(floError(httpError(403), { signIn: true }).kind, 'refused');
  assert.equal(floError(httpError(401)).kind, 'unauthorized');
  assert.equal(floError(httpError(403)).kind, 'unauthorized');
  const cloudFront = floError(
    httpError(403, 'Request blocked', { 'x-cache': 'Error from cloudfront' }),
    {
      signIn: true,
    },
  );
  assert.equal(cloudFront.kind, 'unavailable', 'a CloudFront 403 is not a refusal');
  assert.equal(
    floError(httpError(403, '<html>Generated by cloudfront (CloudFront)</html>')).kind,
    'unavailable',
  );
  assert.equal(floError(httpError(502)).kind, 'unavailable');
  assert.equal(floError(httpError(404), { signIn: true }).kind, 'not_found');
  assert.equal(floError(httpError(418)).kind, 'http');
  const limited = floError(httpError(429, '', { 'retry-after': '120' }));
  assert.equal(limited.kind, 'rate_limited');
  assert.equal(limited.retryAfter, 120_000);
  assert.equal(floError(new NetworkError('timeout', 'slow')).kind, 'timeout');
  // The path only: never the query string.
  assert.equal(httpError(500).message, 'HTTP 500 on /api/v2/x');
});

test('Retry-After as seconds or as a date', () => {
  const at = (value) => retryAfterOf(new Headers({ 'retry-after': value }), NOW);
  assert.equal(at('30'), 30_000);
  assert.equal(at(new Date(NOW + 90_000).toUTCString()), 90_000);
  assert.equal(at('soon'), undefined);
  assert.equal(retryAfterOf(new Headers(), NOW), undefined);
});

test('auto: a retired Flo sign-in (404) falls back to Moen, remembered', async () => {
  const clock = { now: NOW };
  fake = installFlo(clock);
  fake.state.floAuth = 'gone';
  const client = new FloClient({ now: () => clock.now });
  client.configure({ email: EMAIL, password: PASSWORD, loginMethod: 'auto' });
  await client.account();
  assert.equal(client.method, 'moen');
  assert.equal(client.preferred, 'moen');
  // Flo only: the 404 is a refusal of the account (nothing else to try).
  const flo = new FloClient({ now: () => clock.now });
  flo.configure({ email: EMAIL, password: PASSWORD, loginMethod: 'flo' });
  await assert.rejects(flo.account(), (err) => err instanceof FloError && err.kind === 'refused');
});

test('auto: a passing failure of the Flo sign-in does not try Moen', async () => {
  const clock = { now: NOW };
  fake = installFlo(clock);
  fake.route('POST', /users\/auth$/, () => json({}, 503));
  const client = new FloClient({ now: () => clock.now });
  client.configure({ email: EMAIL, password: PASSWORD, loginMethod: 'auto' });
  await assert.rejects(client.account(), (err) => err.kind === 'unavailable');
  assert.equal(fake.made(/oauth2/).length, 0);
});

test('no credentials: nothing is sent', async () => {
  const clock = { now: NOW };
  fake = installFlo(clock);
  const client = new FloClient({ now: () => clock.now });
  client.configure({ email: '', password: '', loginMethod: 'auto' });
  await assert.rejects(client.account(), (err) => err.kind === 'no_credentials');
  assert.equal(fake.calls.length, 0);
});

test('a sign-in answer without a token is a bad answer, not a refusal', async () => {
  const clock = { now: NOW };
  fake = installFlo(clock);
  fake.route('POST', /users\/auth$/, () => ({ ok: true }));
  const client = new FloClient({ now: () => clock.now });
  client.configure({ email: EMAIL, password: PASSWORD, loginMethod: 'flo' });
  await assert.rejects(client.account(), (err) => err.kind === 'bad_response');
});

test('the request times out, and its timer is cleared', async () => {
  const previous = setFetch(
    (url, init) =>
      new Promise((resolve, reject) => {
        init.signal.addEventListener('abort', () =>
          reject(Object.assign(new Error('aborted'), { name: 'AbortError' })),
        );
      }),
  );
  try {
    await assert.rejects(
      request('https://api-gw.meetflo.com/api/v2/alarms', { timeout: 20 }),
      (err) => {
        assert.equal(err.kind, 'timeout');
        return true;
      },
    );
    setFetch(async () => {
      throw Object.assign(new TypeError('fetch failed'), { cause: { code: 'ENOTFOUND' } });
    });
    await assert.rejects(request('https://api-gw.meetflo.com/api/v2/alarms'), (err) => {
      assert.equal(err.kind, 'network');
      assert.match(err.message, /ENOTFOUND/);
      return true;
    });
  } finally {
    setFetch(previous);
  }
});
